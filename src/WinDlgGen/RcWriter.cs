using System.Text;

namespace WinDlgGen;

/// <summary>
/// Writes laid-out dialogs as <c>DIALOGEX</c> resources for the resource
/// compiler.
/// </summary>
/// <remarks>
/// Every control is written as a generic <c>CONTROL</c> statement with all
/// its style flags spelled out. The shorthand statements (<c>LTEXT</c>,
/// <c>PUSHBUTTON</c> and so on) each add their own default flags, which
/// would make the output depend on rules the reader cannot see.
/// <c>CONTROL</c> itself adds only <c>WS_CHILD | WS_VISIBLE</c>.
/// </remarks>
public sealed class RcWriter
{
    private readonly StringBuilder _text = new();
    private readonly DiagnosticBag _diagnostics;

    /// <summary>
    /// Starts the output with a comment saying it is generated.
    /// </summary>
    /// <param name="diagnostics">Receives the problems found while writing.</param>
    public RcWriter(DiagnosticBag diagnostics)
    {
        _diagnostics = diagnostics;
        Line("// Generated by WinDlgGen. Do not edit this file: edit the XML file");
        Line("// named before each dialog, and generate it again.");
        Line();
        // The text of controls is written as UTF-8.
        Line("#pragma code_page(65001)");
    }

    /// <summary>
    /// Copy text from an external source into the output at the current location. 
    /// </summary>
    /// <param name="reader">
    /// Provides the text (file) to append.  It will be re-encoded into the output. 
    /// </param>
    /// <param name="comment">
    /// Comment on the textual inclusion that will be inserted into the output.
    /// </param>
    public void CopyVerbatim(TextReader reader, string comment)
    {
        Line($"// BEGIN file inclusion: {comment}");
        Line();
        
        while (reader.ReadLine() is { } line)
            Line(line);
        
        Line();
        Line($"// END file inclusion: {comment}");
    }

    /// <summary>
    /// Appends one dialog.
    /// </summary>
    /// <param name="dialog">A dialog that <see cref="Layout.Run"/> has laid
    /// out without errors.</param>
    /// <param name="sourceName">The XML file it came from, for the comment
    /// before it.</param>
    public void Add(DialogNode dialog, string sourceName)
    {
        Line();
        Line($"// From {sourceName}");
        Line($"{dialog.Id} DIALOGEX 0, 0, {dialog.Bounds.Width}, {dialog.Bounds.Height}");
        Line($"STYLE {string.Join(" | ", dialog.Style)}");
        if (dialog.ExStyle is not null)
            Line($"EXSTYLE {dialog.ExStyle}");
        if (dialog.Caption is not null)
            Line($"CAPTION {Quote(dialog.Caption)}");
        // Weight 0 is the default; charset 1 is DEFAULT_CHARSET.
        Line($"FONT {dialog.FontSize}, {Quote(dialog.FontFace)}, 0, 0, 0x1");
        Line("BEGIN");

        ControlSpec? previous = null;
        foreach (var (spec, bounds, location) in Controls(dialog))
        {
            WriteControl(spec, bounds, previous, location);
            previous = spec;
        }

        Line("END");
    }

    /// <summary>
    /// The text written so far, with Windows line endings.
    /// </summary>
    public override string ToString() => _text.ToString();

    /// <summary>
    /// The controls of a dialog in tab order, which is the order of the
    /// tree with each group box before its contents, with the rectangle
    /// to write for each.
    /// </summary>
    private static IEnumerable<(ControlSpec Spec, Rect Bounds, SourceLocation Location)> Controls(Node node)
    {
        switch (node)
        {
            case ControlNode control:
                var b = control.Bounds;
                yield return (control.Spec, b with { Height = b.Height + control.ExtraHeight }, control.Location);
                break;

            case StackNode stack:
                if (stack is GroupNode group)
                    yield return (group.Box, group.Bounds, group.Location);
                foreach (var child in stack.Children)
                {
                    foreach (var item in Controls(child))
                        yield return item;
                }
                break;
        }
    }

    /// <summary>
    /// Writes one <c>CONTROL</c> statement, working out <c>WS_GROUP</c> and
    /// <c>WS_TABSTOP</c> where the XML leaves them out.
    /// </summary>
    /// <param name="spec">The control.</param>
    /// <param name="bounds">The rectangle to write for it.</param>
    /// <param name="previous">The control before it in tab order, or null
    /// for the first.</param>
    /// <param name="location">Where the control is in the XML, for diagnostics.</param>
    /// <remarks>
    /// <para>
    /// The dialog manager treats the controls from one with
    /// <c>WS_GROUP</c> up to the next one with it as a group, within which
    /// the arrow keys move. Radio buttons must therefore be grouped, and
    /// nothing else should share their group. So by default every control
    /// starts a group, except a radio button following another radio
    /// button: a run of adjacent radio buttons forms one group.
    /// </para>
    /// <para>
    /// Controls the user can interact with are tab stops. Of a group of
    /// radio buttons, only the first is: tabbing into the group then moves
    /// to whichever button is checked.
    /// </para>
    /// </remarks>
    private void WriteControl(ControlSpec spec, Rect bounds, ControlSpec? previous, SourceLocation location)
    {
        bool group = spec.Group ?? (spec.Kind != ControlKind.Radio || previous?.Kind != ControlKind.Radio);
        bool tabStop = spec.TabStop ?? spec.Kind switch
        {
            ControlKind.Button or ControlKind.CheckBox or ControlKind.Edit
                or ControlKind.ComboBox or ControlKind.ListBox or ControlKind.Trackbar => true,
            ControlKind.Radio => group,
            _ => false,
        };

        List<string> style = [.. spec.Style];
        if (group)
            style.Add("WS_GROUP");
        if (tabStop)
            style.Add("WS_TABSTOP");
        if (!spec.Enabled)
            style.Add("WS_DISABLED");
        // Last, so that it clears the WS_VISIBLE that CONTROL adds by default.
        if (!spec.Visible)
            style.Add("NOT WS_VISIBLE");
        var styleText = style.Count > 0 ? string.Join(" | ", style) : "0";

        if (bounds.Bottom > Units.Max || bounds.Right > Units.Max)
        {
            _diagnostics.Error(DiagnosticCodes.TooLarge, location,
                $"The control extends to ({bounds.Right}, {bounds.Bottom}), "
                + $"beyond the {Units.Max} dialog units a template can hold");
        }

        var line = $"    CONTROL {Quote(spec.Text)}, {spec.Id}, {Quote(spec.ClassName)}, {styleText}, "
                   + $"{bounds.X}, {bounds.Y}, {bounds.Width}, {bounds.Height}";
        if (spec.ExStyle is not null)
            line += $", {spec.ExStyle}";
        Line(line);
    }

    /// <summary>
    /// Quotes text as a string for the resource compiler, which reads
    /// <c>""</c> as a quotation mark and C escape sequences after a
    /// backslash.
    /// </summary>
    /// <remarks>
    /// Precondition: the only control characters in <paramref name="s"/>
    /// are newline and tab, as the reader ensures.
    /// </remarks>
    public static string Quote(string s)
    {
        var b = new StringBuilder(s.Length + 2);
        b.Append('"');
        foreach (char c in s)
        {
            switch (c)
            {
                case '"': b.Append("\"\""); break;
                case '\\': b.Append(@"\\"); break;
                case '\n': b.Append(@"\n"); break;
                case '\t': b.Append(@"\t"); break;
                default: b.Append(c); break;
            }
        }
        b.Append('"');
        return b.ToString();
    }

    private void Line(string s = "") => _text.Append(s).Append("\r\n");
}
